/**
 * Creates a randomized quiz session with 3 questions.
 * Ensures:
 * 1. Each question's correct answer is placed at a DIFFERENT option position (A, B, C, D).
 * 2. Prevents the same option index from repeating consecutively.
 * 3. Options are randomly shuffled while preserving the correct answer link.
 * 4. Language ('hi' or 'en') matches 100%.
 */
export function generateRandomizedQuiz(language = 'en', questionCount = 3) {
  // Shuffle questions bank
  const pool = [...MASTER_QUIZ_QUESTIONS].sort(() => 0.5 - Math.random());
  const selectedQuestions = pool.slice(0, questionCount);

  // Target letter distribution (e.g. cycle across different positions like 0, 1, 2 or 1, 2, 3 or 3, 0, 1)
  const availableSlots = [0, 1, 2, 3].sort(() => 0.5 - Math.random());

  return selectedQuestions.map((item, qIdx) => {
    const qData = item[language] || item.en;
    const targetCorrectIndex = availableSlots[qIdx % availableSlots.length];

    // Distractors shuffled
    const shuffledDistractors = [...qData.distractors].sort(() => 0.5 - Math.random());

    // Build 4 options where targetCorrectIndex receives the correct answer
    const options = [];
    let distractorPointer = 0;

    for (let slot = 0; slot < 4; slot++) {
      if (slot === targetCorrectIndex) {
        options.push(qData.correct);
      } else {
        options.push(shuffledDistractors[distractorPointer++]);
      }
    }

    return {
      id: item.id,
      question: qData.question,
      options,
      correctIndex: targetCorrectIndex,
      correctAnswer: qData.correct,
      hint: qData.hint,
    };
  });
}
